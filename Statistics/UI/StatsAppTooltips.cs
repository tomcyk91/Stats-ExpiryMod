        private void AttachChartMetricTooltip(TextMeshProUGUI label)
        {
            if (label == null || _categoryCycleBtn == null) return;
            string metric = GetActiveChartMetricLabel();
            if (!TryGetChartMetricTooltip(metric, out string title, out string body)) return;

            // IMPORTANT: nie tworzymy tutaj przezroczystej strefy EventTrigger jako
            // dziecka przycisku. EventTrigger implementuje IPointerClickHandler i wtedy
            // przechwytuje kliknięcie zanim trafi ono do Buttona „Kategoria”.
            // Tooltip podpinamy bezpośrednio do tego samego GameObject co Button.
            label.raycastTarget = false;

            RectTransform buttonRT = _categoryCycleBtn.GetComponent<RectTransform>();
            if (buttonRT == null) return;

            var trigger = _categoryCycleBtn.GetComponent<EventTrigger>();
            if (trigger == null)
                trigger = _categoryCycleBtn.gameObject.AddComponent<EventTrigger>();

            // Ten EventTrigger należy tylko do naszego przycisku kategorii.
            // Czyścimy poprzednie wpisy, bo etykieta/metryka jest aktualizowana po kliknięciu.
            trigger.triggers.Clear();

            AddTooltipEvent(trigger, EventTriggerType.PointerEnter,
                (UnityAction<BaseEventData>)((_) => ShowProductInfoTooltip(buttonRT, buttonRT, title, body)));
            AddTooltipEvent(trigger, EventTriggerType.PointerExit,
                (UnityAction<BaseEventData>)((_) => HideProductInfoTooltip()));
        }

