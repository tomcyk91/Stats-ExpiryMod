        private Transform BeginMetricTooltipRoot(TextMeshProUGUI tmp, string rootName)
        {
            if (tmp == null) return null;

            Transform old = tmp.transform.Find(rootName);
            if (old != null)
                UnityEngine.Object.Destroy(old.gameObject);

            var root = new GameObject(rootName);
            root.transform.SetParent(tmp.transform, false);

            RectTransform rt = root.AddComponent<RectTransform>();
            rt.anchorMin = Vector2.zero;
            rt.anchorMax = Vector2.one;
            rt.offsetMin = Vector2.zero;
            rt.offsetMax = Vector2.zero;
            return root.transform;
        }

        private void CreateMetricLineZone(
            Transform root,
            RectTransform tileRT,
            string name,
            int lineIndex,
            int lineCount,
            float xMin,
            float xMax,
            string title,
            string body)
        {
            if (root == null || lineCount <= 0 || lineIndex < 0 || lineIndex >= lineCount) return;

            float yMax = 1f - lineIndex / (float)lineCount;
            float yMin = 1f - (lineIndex + 1) / (float)lineCount;

            CreateProductInfoTooltipZone(
                root,
                tileRT,
                name,
                new Vector2(Mathf.Clamp01(xMin), yMin),
                new Vector2(Mathf.Clamp01(xMax), yMax),
                title,
                body);
        }

