        private void AttachExpirationInfoTooltipZones(
            Transform tile,
            TextMeshProUGUI infoTmp,
            SortedDictionary<int, int> shelfBatches,
            SortedDictionary<int, int> boxBatches)
        {
            if (tile == null || infoTmp == null) return;

            Transform root = BeginMetricTooltipRoot(infoTmp, "ExpirationMetricTooltipZones");
            if (root == null) return;

            RectTransform tileRT = tile.GetComponent<RectTransform>();

            int shelfLines = CountExpirationSectionLines(shelfBatches);
            int boxLines = CountExpirationSectionLines(boxBatches);
            int totalLines = Mathf.Max(1, shelfLines + boxLines);

            float shelfBottom = 1f - shelfLines / (float)totalLines;

            CreateProductInfoTooltipZone(
                root,
                tileRT,
                "ExpiryShelfSection",
                new Vector2(0f, shelfBottom),
                new Vector2(1f, 1f),
                Plugin.T("Terminy na półce", "Shelf expiry dates"),
                Plugin.T(
                    "Pokazuje terminy produktów, które fizycznie znajdują się na półkach lub ekspozycjach sklepu. Daty są posortowane od najpilniejszej. Jeżeli widzisz „+N termin.”, produkt ma jeszcze dodatkowe grupy terminów, których nie pokazujemy na karcie, aby zachować czytelność.",
                    "Shows expiry dates for products physically placed on store shelves or displays. Dates are sorted from the most urgent. “+N more” means there are additional expiry groups hidden to keep the card readable."));

            CreateProductInfoTooltipZone(
                root,
                tileRT,
                "ExpiryBoxesSection",
                new Vector2(0f, 0f),
                new Vector2(1f, shelfBottom),
                Plugin.T("Terminy w kartonach", "Box expiry dates"),
                Plugin.T(
                    "Pokazuje terminy produktów, które nadal znajdują się w kartonach. Obejmuje fizyczne kartony obecne w scenie, dla których mod ma zapisane daty ważności. Daty są posortowane od najpilniejszej.",
                    "Shows expiry dates for products still stored in boxes. It includes physical boxes present in the scene for which the mod has saved expiry dates. Dates are sorted from the most urgent."));
        }

        private void AttachIceCreamInfoTooltipZones(Transform tile, TextMeshProUGUI infoTmp, string body)
        {
            if (tile == null || infoTmp == null || string.IsNullOrEmpty(body)) return;
            Transform root = BeginMetricTooltipRoot(infoTmp, "IceCreamMetricTooltipZones");
            if (root == null) return;
            RectTransform tileRT = tile.GetComponent<RectTransform>();

            string[] lines = body.Split('\n');
            int lineCount = Mathf.Max(1, lines.Length);

            for (int i = 0; i < lines.Length; i++)
            {
                string line = lines[i] ?? string.Empty;

                if (line.Contains(Plugin.T("Sprzedane", "Sold")))
                    CreateMetricLineZone(root, tileRT, "IceSold_" + i, i, lineCount, 0.00f, 0.30f,
                        Plugin.T("Sprzedane lody", "Ice creams sold"),
                        Plugin.T("Liczba gotowych lodów sprzedanych dla tego podsumowania, rożka lub kombinacji.", "Number of finished ice creams sold for this summary, cone, or combination."));

                if (line.Contains(Plugin.T("Lody", "Ice creams")) && !line.Contains(Plugin.T("Lody z tym smakiem", "Ice creams with flavour")))
                    CreateMetricLineZone(root, tileRT, "IceCount_" + i, i, lineCount, 0.00f, 0.30f,
                        Plugin.T("Lody", "Ice creams"),
                        Plugin.T("Liczba gotowych lodów wykorzystujących wskazany rożek.", "Number of finished ice creams using the selected cone."));

                if (line.Contains(Plugin.T("Przychód", "Revenue")) && !line.Contains(Plugin.T("Przychód / Koszt", "Revenue / Cost")))
                    CreateMetricLineZone(root, tileRT, "IceRevenue_" + i, i, lineCount, 0.00f, 0.38f,
                        Plugin.T("Przychód", "Revenue"),
                        Plugin.T("Łączna kwota zapłacona przez klientów za te gotowe lody.", "Total amount paid by customers for these finished ice creams."));

                if (line.Contains(Plugin.T("Koszt", "Cost")) && !line.Contains(Plugin.T("Przychód / Koszt", "Revenue / Cost")))
