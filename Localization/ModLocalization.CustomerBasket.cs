        private static void SetCustomerBasketTerms(
            string code,
            string customers,
            string transactions,
            string averageBasket,
            string itemsPerBasket,
            string revenuePerCustomer,
            string satisfaction,
            string notFoundRate,
            string tooExpensiveRate,
            string completedCheckoutTransactions,
            string items,
            string customersRecordedByGame,
            string noTransactionData)
        {
            if (!Packs.TryGetValue(code, out LanguagePack pack) || pack == null)
                return;

            pack.Terms["customers"] = customers;
            pack.Terms["transactions"] = transactions;
            pack.Terms["average basket"] = averageBasket;
            pack.Terms["items per basket"] = itemsPerBasket;
            pack.Terms["revenue per customer"] = revenuePerCustomer;
            pack.Terms["satisfaction"] = satisfaction;
            pack.Terms["not found rate"] = notFoundRate;
            pack.Terms["too expensive rate"] = tooExpensiveRate;
            pack.Terms["completed checkout transactions"] = completedCheckoutTransactions;
            pack.Terms["items"] = items;
            pack.Terms["customers recorded by the game"] = customersRecordedByGame;
            pack.Terms["no transaction data"] = noTransactionData;
        }
